"""```markdown
### Table 1: Predictability by Pitcher
Predictability (%) is the percentage of pitches belonging to the most common pitch type across all pitches by that pitcher in this dataset. Tied pitch types are listed together. Total pitches are included to show the sample size; no minimum sample-size cutoff is applied.
```
"""

group_columns = ['pitcher', 'player_name']

# Count each pitch type across all counts for each pitcher.
pitch_counts = pd.crosstab(
    [tor_pitchers_clean[column] for column in group_columns],
    tor_pitchers_clean['pitch_type']
)
most_common_count = pitch_counts.max(axis=1)

predictability_table = pd.DataFrame({
    'total_pitches': pitch_counts.sum(axis=1),
    'most_common_pitch_type': pitch_counts.apply(
        lambda row: ', '.join(row.index[row.eq(row.max())]), axis=1
    ),
    'predictability_pct': most_common_count / pitch_counts.sum(axis=1) * 100
}).reset_index().sort_values(
    'total_pitches', ascending=False
).reset_index(drop=True)

display(predictability_table.round(2))

"""```markdown
### Graph 1: Pitch Predictability by Pitcher
Labels include the most-used pitch type and total pitches. Correlation is not applicable to a bar chart of pitcher names.
```
"""

# Sort pitchers by reliance on their most-used pitch type.
plot_data = predictability_table.sort_values('predictability_pct')
labels = (
    plot_data['player_name'] + ' (' + plot_data['most_common_pitch_type']
    + '; n=' + plot_data['total_pitches'].astype(str) + ')'
)
fig, ax = plt.subplots(figsize=(12, 8))
bars = ax.barh(labels, plot_data['predictability_pct'], color='#1976b9')
ax.bar_label(bars, fmt='%.1f%%', padding=4)
ax.set_title('Blue Jays Pitch Predictability by Pitcher — 2025 Postseason', fontweight='bold')
ax.set_xlabel('Pitches using the most common pitch type (%)')
ax.set_ylabel('Pitcher (most-used pitch type; n = total pitches)')
ax.set_xlim(0, 110)
ax.set_xticks(range(0, 101, 20))
ax.grid(axis='x', alpha=0.2)
ax.set_axisbelow(True)
plt.tight_layout()
plt.show()

"""```markdown
### Table 2: Predictability and Whiff Rate
Whiff rate (%) = missed swings / total swings × 100. Missed swings include swinging_strike, swinging_strike_blocked, and missed_bunt. Swings also include fouls, foul tips, foul bunts, bunt foul tips, and balls hit into play. A pitcher with no swings has a missing whiff rate rather than 0%.
```
"""

whiff_descriptions = ['swinging_strike', 'swinging_strike_blocked', 'missed_bunt']
swing_descriptions = whiff_descriptions + [
    'foul', 'foul_tip', 'foul_bunt', 'bunt_foul_tip', 'hit_into_play'
]

tor_pitchers_clean['is_swing'] = tor_pitchers_clean['description'].isin(swing_descriptions)
tor_pitchers_clean['is_whiff'] = tor_pitchers_clean['description'].isin(whiff_descriptions)

swing_counts = tor_pitchers_clean.groupby(group_columns).agg(
    total_swings=('is_swing', 'sum'),
    missed_swings=('is_whiff', 'sum')
).reset_index()
swing_counts['whiff_rate_pct'] = (
    swing_counts['missed_swings']
    / swing_counts['total_swings'].where(swing_counts['total_swings'].gt(0)) * 100
)

whiff_table = predictability_table[
    group_columns + ['total_pitches', 'predictability_pct']
].merge(swing_counts, on=group_columns, how='left', validate='one_to_one')

display(whiff_table.round(2))

"""```markdown
### Graph 2: Predictability and Whiff Rate
Each point is one pitcher. Labels show the pitcher’s surname and number of swings (n). The fitted line extends across the plotting area; outside the observed predictability values it is an extrapolation. Pearson’s r uses one observation per pitcher, with equal weight.
```
"""

plot_data = whiff_table.dropna(subset=['predictability_pct', 'whiff_rate_pct'])
fig, ax = plt.subplots(figsize=(12, 8))
ax.scatter(plot_data['predictability_pct'], plot_data['whiff_rate_pct'],
           color='#1976b9', s=70, alpha=0.8, edgecolors='white')
for _, row in plot_data.iterrows():
    label = row['player_name'].split(',')[0] + ' (n=' + str(int(row['total_swings'])) + ')'
    ax.annotate(label, (row['predictability_pct'], row['whiff_rate_pct']),
                xytext=(-8, 6) if row['player_name'].split(',')[0] in ['Little', 'Varland', 'Lauer'] else (5, 6),
                ha='right' if row['player_name'].split(',')[0] in ['Little', 'Varland', 'Lauer'] else 'left',
                textcoords='offset points', fontsize=9)
ax.set_title('Blue Jays Pitch Predictability and Whiff Rate — 2025 Postseason', fontweight='bold')
ax.set_xlabel('Predictability: pitches using the most common pitch type (%)')
ax.set_ylabel('Whiff rate: missed swings / total swings (%)')
ax.set_xlim(0, 110)
ax.set_xticks(range(0, 101, 20))
ax.set_ylim(0, max(50, plot_data['whiff_rate_pct'].max() + 10))

# Pearson correlation across pitchers, using equal weights.
x = plot_data['predictability_pct']
y = plot_data['whiff_rate_pct']
pearson_r = x.corr(y)

# Fit a straight line to the same pitcher-level observations.
slope, intercept = np.polyfit(x, y, 1)
x_line = np.linspace(*ax.get_xlim(), 200)
ax.plot(x_line, slope * x_line + intercept, color='#b3261e', linewidth=2,
        label='Linear trend')
ax.text(0.98, 0.97, f'Pearson r = {pearson_r:.6f}\nPitchers = {len(plot_data)}',
        transform=ax.transAxes, ha='right', va='top',
        bbox=dict(facecolor='white', edgecolor='lightgray', alpha=0.95))
ax.legend(loc='lower right')
ax.grid(alpha=0.2)
ax.set_axisbelow(True)
plt.tight_layout()
plt.show()

"""```markdown
### Pearson Correlation Calculation (Whiff Rate)
Each pitcher receives equal weight. Here $x$ is predictability (%) and $y$ is the outcome plotted above.
```
"""

x_mean = x.mean()
y_mean = y.mean()
x_deviation = x - x_mean
y_deviation = y - y_mean

correlation_working = pd.DataFrame({
    'pitcher': plot_data['player_name'],
    'x': x,
    'y': y,
    'x_minus_mean': x_deviation,
    'y_minus_mean': y_deviation,
    'deviation_product': x_deviation * y_deviation,
    'x_deviation_squared': x_deviation ** 2,
    'y_deviation_squared': y_deviation ** 2
})
print(correlation_working.to_string(index=False, float_format=lambda value: f'{value:.6f}'))

sum_products = (x_deviation * y_deviation).sum()
sum_x_squared = (x_deviation ** 2).sum()
sum_y_squared = (y_deviation ** 2).sum()
denominator = np.sqrt(sum_x_squared * sum_y_squared)
manual_r = sum_products / denominator

print(f'\nNumber of pitchers = {len(plot_data)}')
print(f'Mean x = {x_mean:.8f}; mean y = {y_mean:.8f}')
print(f'Sum of deviation products = {sum_products:.8f}')
print(f'Sum of squared x deviations = {sum_x_squared:.8f}')
print(f'Sum of squared y deviations = {sum_y_squared:.8f}')
print(f'\nr = {sum_products:.8f} / sqrt({sum_x_squared:.8f} * {sum_y_squared:.8f})')
print(f'r = {sum_products:.8f} / {denominator:.8f}')
print(f'r = {manual_r:.10f}')
print(f'Pandas correlation check = {x.corr(y):.10f}')
assert np.isclose(manual_r, x.corr(y))

